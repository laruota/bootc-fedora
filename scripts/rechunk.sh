#!/usr/bin/env bash
# Rechunk a bootc image with `rpm-ostree compose build-chunked-oci`.
#
# Usage: scripts/rechunk.sh <image> <source-tag> [target-tag]
#
# The source image must be in the local podman storage and contain
# /usr/bin/rpm-ostree (all Fedora bootc/Silverblue images do). The output is a
# content-based ("chunked") image: unchanged RPMs stay in identical layers, so
# `bootc upgrade` on the target downloads only what actually changed.
#
# The rechunker runs from the image itself and reads the mounted image as a
# rootfs. This works with rootless podman and does not need rpm-ostree on the
# host (same approach as ublue-os/image-template).
#
# `--rootfs` creates a fresh OCI config, so Cmd/Env are not inherited; the
# labels that describe the image/build are preserved explicitly below. bootc
# does not use Cmd/Env, so the published OS image is unaffected.
#
# Environment:
#   PREVIOUS_BUILD           optional remote ref (e.g.
#                            docker://ghcr.io/org/image:45) used with
#                            --previous-build to keep the layer plan stable
#                            across builds. Must point to a previously chunked
#                            build: here the label org.bootc-fedora.rechunked=1
#                            is the quick check, while build-chunked-oci also
#                            requires the ostree.components annotation on every
#                            layer (the push must preserve it).
#                            Skipped otherwise or when skopeo is unavailable.
#   RECHUNK_OCI_DIR          optional directory: write an OCI layout there
#                            instead of importing into containers-storage. CI
#                            uses it because the containers-storage transport of
#                            older containers/image drops layer annotations when
#                            copying, while an OCI layout keeps them.
#   RECHUNK_MAX_LAYERS       default 127
#   RECHUNK_FORMAT_VERSION   default 2
set -euo pipefail

IMAGE="${1:?Uso: $0 <image> <source-tag> [target-tag]}"
SOURCE_TAG="${2:?Uso: $0 <image> <source-tag> [target-tag]}"
TARGET_TAG="${3:-$SOURCE_TAG}"

MAX_LAYERS="${RECHUNK_MAX_LAYERS:-127}"
FORMAT_VERSION="${RECHUNK_FORMAT_VERSION:-2}"
OUTPUT_OCI_DIR="${RECHUNK_OCI_DIR:-}"

die() {
    echo "errore: $*" >&2
    exit 1
}

podman image exists "$IMAGE:$SOURCE_TAG" \
    || die "immagine non trovata: $IMAGE:$SOURCE_TAG"

# rpm-ostree is needed inside the image; check before doing any work.
podman run --rm --pull=never --entrypoint /bin/sh "$IMAGE:$SOURCE_TAG" \
    -c 'test -x /usr/bin/rpm-ostree' \
    || die "$IMAGE:$SOURCE_TAG non contiene /usr/bin/rpm-ostree"

# The rechunker regenerates ostree/rpmostree metadata, and --bootc adds
# containers.bootc=1. Preserve every other label (OCI metadata, base digest,
# custom labels) so the published image keeps its build provenance.
source_has_base_digest=0
if [ -n "$(podman image inspect --format \
    '{{with .Config.Labels}}{{index . "org.opencontainers.image.base.digest"}}{{end}}' \
    "$IMAGE:$SOURCE_TAG" 2>/dev/null)" ]; then
    source_has_base_digest=1
fi

labels=()
while IFS= read -r kv; do
    [ -n "$kv" ] || continue
    case "$kv" in
        # Regenerated by the rechunker / --bootc, stale for the new commit, or
        # set explicitly below.
        containers.bootc=* | ostree.commit=* | ostree.final-diffid=* | \
            rpmostree.* | io.buildah.version=* | org.bootc-fedora.rechunked=*)
            continue
            ;;
    esac
    labels+=("--label=$kv")
done < <(podman image inspect --format \
    '{{range $k,$v := .Config.Labels}}{{$k}}={{$v}}{{"\n"}}{{end}}' \
    "$IMAGE:$SOURCE_TAG")
labels+=("--label=org.bootc-fedora.rechunked=1")

GRAPHROOT="$(podman info --format '{{.Store.GraphRoot}}')"
[ -n "$GRAPHROOT" ] || die "impossibile leggere lo GraphRoot di podman"

# Optional: anchor the layer plan to the previously published build. This
# avoids reshuffling many layers when the package set changes.
previous=()
auth_args=()
if [ -n "${PREVIOUS_BUILD:-}" ]; then
    # Only anchor to a previously *chunked* build: using an unchunked image as
    # baseline would inherit its coarse layer plan. skopeo can read the remote
    # config without pulling layers; without skopeo we skip the option (the
    # content-based plan is deterministic anyway).
    previous_is_chunked=0
    if command -v skopeo >/dev/null 2>&1; then
        previous_config="$(skopeo inspect --config "$PREVIOUS_BUILD" 2>/dev/null || true)"
        case "$previous_config" in
            *'"org.bootc-fedora.rechunked"'*) previous_is_chunked=1 ;;
        esac
    fi
    if [ "$previous_is_chunked" = 1 ]; then
        previous=(--previous-build "$PREVIOUS_BUILD")
        authfile="${REGISTRY_AUTH_FILE:-}"
        if [ -z "$authfile" ]; then
            for candidate in \
                "${XDG_RUNTIME_DIR:-/run/user/$(id -u)}/containers/auth.json" \
                "$HOME/.config/containers/auth.json"; do
                if [ -f "$candidate" ]; then
                    authfile="$candidate"
                    break
                fi
            done
        fi
        if [ -n "$authfile" ] && [ -f "$authfile" ]; then
            auth_args=(
                --volume "$authfile:/run/containers/auth.json:ro"
                --env REGISTRY_AUTH_FILE=/run/containers/auth.json
            )
        fi
        echo "rechunk: previous build $PREVIOUS_BUILD"
    else
        echo "rechunk: previous build non chunked o non raggiungibile, proseguo senza" >&2
    fi
fi

echo "rechunk: $IMAGE:$SOURCE_TAG -> $IMAGE:$TARGET_TAG (format v$FORMAT_VERSION, max $MAX_LAYERS layers)"

output_mount=()
if [ -n "$OUTPUT_OCI_DIR" ]; then
    # OCI layout: keeps the `ostree.components` annotations, which the
    # containers-storage transport of older containers/image drops on copy.
    mkdir -p "$OUTPUT_OCI_DIR"
    output_mount=(--mount "type=bind,src=$OUTPUT_OCI_DIR,target=/run/rechunk-output,rw")
    output_args=(--output "oci:/run/rechunk-output:$TARGET_TAG")
    output_ref="oci:$OUTPUT_OCI_DIR:$TARGET_TAG"
else
    # GraphRoot is bind-mounted so the output image lands in the host podman
    # storage. /run/rpm-ostree-storage is only the transient runroot.
    output_args=(--output "containers-storage:[overlay@/run/host-container-storage+/run/rpm-ostree-storage]${IMAGE}:${TARGET_TAG}")
    output_ref="containers-storage:$IMAGE:$TARGET_TAG"
fi

podman run --rm --pull=never --privileged --security-opt label=disable \
    --mount=type=image,src="$IMAGE:$SOURCE_TAG",target=/rpm-ostree \
    --mount=type=bind,src="$GRAPHROOT",target=/run/host-container-storage,rw \
    --mount=type=tmpfs,target=/run/rpm-ostree-storage \
    "${output_mount[@]}" \
    "${auth_args[@]}" \
    --entrypoint /usr/bin/rpm-ostree \
    "$IMAGE:$SOURCE_TAG" \
    compose build-chunked-oci \
    --bootc \
    --format-version="$FORMAT_VERSION" \
    --max-layers="$MAX_LAYERS" \
    --rootfs /rpm-ostree \
    "${previous[@]}" \
    "${labels[@]}" \
    "${output_args[@]}"

# Sanity checks: bootc refuses images without containers.bootc=1, and the
# README promises the base digest label for published images.
required_labels=(containers.bootc ostree.commit)
if [ "$source_has_base_digest" = 1 ]; then
    required_labels+=(org.opencontainers.image.base.digest)
fi

# Read labels and the manifest from whichever transport holds the output. For
# the OCI layout skopeo is mandatory (the annotations are the point of that
# mode); for containers-storage it is optional and only used for annotations.
manifest_json=""
if [ -n "$OUTPUT_OCI_DIR" ]; then
    command -v skopeo >/dev/null 2>&1 || die "skopeo è richiesto con RECHUNK_OCI_DIR"
    labels_json="$(skopeo inspect --config "$output_ref" \
        | python3 -c 'import json,sys; print(json.dumps((json.load(sys.stdin).get("config") or {}).get("Labels") or {}))')"
    manifest_json="$(skopeo inspect --raw "$output_ref")"
else
    labels_json="$(podman image inspect --format '{{json .Config.Labels}}' "$IMAGE:$TARGET_TAG")"
    if command -v skopeo >/dev/null 2>&1; then
        manifest_json="$(skopeo inspect --raw "containers-storage:$IMAGE:$TARGET_TAG")"
    fi
fi

missing_labels="$(printf '%s' "$labels_json" | python3 -c 'import json,sys; labels=json.load(sys.stdin) or {}; print(" ".join(label for label in sys.argv[1:] if not labels.get(label)))' "${required_labels[@]}")"
[ -z "$missing_labels" ] || die "label mancanti nell'immagine rechunkata: $missing_labels"

# `build-chunked-oci --previous-build` riusa il piano dei layer solo se ogni
# layer (tranne il primo, quello dei metadati ostree) porta l'annotazione
# `ostree.components`. Il push deve conservarla: senza, la build successiva
# ricalcola il piano da zero e gli upgrade tornano da ~1 GB.
if [ -n "$manifest_json" ]; then
    missing_annotations="$(printf '%s' "$manifest_json" | python3 -c 'import json,sys; layers=json.load(sys.stdin).get("layers",[]); print(sum(1 for layer in layers[1:] if "ostree.components" not in (layer.get("annotations") or {})))')"
    [ "$missing_annotations" = 0 ] || die "$missing_annotations layer senza annotazione ostree.components: il piano dei layer non sarebbe riutilizzabile"
    layers="$(printf '%s' "$manifest_json" | python3 -c 'import json,sys; print(len(json.load(sys.stdin).get("layers",[])))')"
else
    echo "rechunk: skopeo assente, salto il controllo delle annotazioni ostree.components" >&2
    layers="$(podman image inspect --format '{{len .RootFS.Layers}}' "$IMAGE:$TARGET_TAG")"
fi

echo "rechunk: immagine pronta ($layers layer)"

# The source is the intermediate (non-chunked) build: it is no longer needed
# once the chunked image exists. In-place rechunk (same tag) keeps it.
if [ "$SOURCE_TAG" != "$TARGET_TAG" ]; then
    podman rmi "$IMAGE:$SOURCE_TAG" >/dev/null 2>&1 || true
fi
